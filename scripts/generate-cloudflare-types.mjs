#!/usr/bin/env node

import { existsSync, mkdirSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { join, resolve } from "node:path";
import { spawnSync } from "node:child_process";

const checkOnly = process.argv.includes("--check");
const workspace = process.cwd();
const canonicalConfigPath = resolve(workspace, "wrangler.jsonc");
const tempDirectory = resolve(workspace, ".wrangler");
const tempConfigPath = join(tempDirectory, "typegen-config.jsonc");
const outputPath = resolve(workspace, "cloudflare-env.d.ts");
const generatedPath = join(tempDirectory, "cloudflare-env.d.ts");
const stableHeader = [
  "/* eslint-disable */",
  "// Generated by scripts/generate-cloudflare-types.mjs. The Wrangler command line is omitted because it contains the machine path.",
  "",
].join("\n");

const normalizeTypes = (text) => {
  const body = text
    .replace(/^\uFEFF/, "")
    .replace(/\r\n/g, "\n")
    .replace(/^\/\* eslint-disable \*\/\n\/\/ Generated by [^\n]*\n+/, "");
  return `${stableHeader}${body}`;
};
const wranglerBin = resolve(
  workspace,
  "node_modules",
  "wrangler",
  "bin",
  "wrangler.js",
);

if (!existsSync(canonicalConfigPath)) {
  console.error("Missing canonical wrangler.jsonc");
  process.exit(2);
}

if (!existsSync(wranglerBin)) {
  console.error("Missing local Wrangler CLI. Run npm ci first.");
  process.exit(2);
}

const config = JSON.parse(readFileSync(canonicalConfigPath, "utf8"));

// The canonical main points at the generated OpenNext worker. Wrangler changes
// the self-service binding type depending on whether that build artifact exists.
// A missing typegen-only main keeps the output stable before and after builds.
config.main = "typegen-placeholder.js";

mkdirSync(tempDirectory, { recursive: true });
writeFileSync(tempConfigPath, JSON.stringify(config, null, 2) + "\n", "utf8");

let exitCode = 0;
try {
  const args = [
    wranglerBin,
    "types",
    generatedPath,
    "--config",
    tempConfigPath,
    "--env-interface",
    "CloudflareEnv",
    "--include-runtime=false",
  ];

  const result = spawnSync(process.execPath, args, {
    cwd: workspace,
    stdio: "inherit",
    env: process.env,
  });

  if (result.error) {
    console.error(`Failed to run Wrangler: ${result.error.message}`);
    exitCode = 1;
  } else if ((result.status ?? 1) !== 0) {
    exitCode = result.status ?? 1;
  } else {
    const generated = normalizeTypes(readFileSync(generatedPath, "utf8"));
    if (checkOnly && (!existsSync(outputPath) || normalizeTypes(readFileSync(outputPath, "utf8")) !== generated)) {
      console.error("cloudflare-env.d.ts is out of date. Run node scripts/generate-cloudflare-types.mjs");
      exitCode = 1;
    } else if (!checkOnly) {
      writeFileSync(outputPath, generated, "utf8");
    }
  }
} finally {
  rmSync(tempConfigPath, { force: true });
  rmSync(generatedPath, { force: true });
}

process.exit(exitCode);
